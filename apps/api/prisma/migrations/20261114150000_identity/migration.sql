-- Authentication and its audit commit together, including provider-driven revocation.
CREATE FUNCTION audit_session_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO authentication_audit (id, "userId", action, "occurredAt")
    VALUES (gen_random_uuid()::text, NEW."userId", 'SESSION_CREATED', CURRENT_TIMESTAMP);
    RETURN NEW;
  ELSE
    INSERT INTO authentication_audit (id, "userId", action, "occurredAt")
    VALUES (gen_random_uuid()::text, OLD."userId", 'SESSION_REVOKED', CURRENT_TIMESTAMP);
    RETURN OLD;
  END IF;
END;
$$;
CREATE TRIGGER session_audit AFTER INSERT OR DELETE ON "session"
FOR EACH ROW EXECUTE FUNCTION audit_session_change();
